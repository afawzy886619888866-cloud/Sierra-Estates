/** Roles that may enter the staff admin portal after Firebase authentication. */
export const ADMIN_PORTAL_ROLES = ["owner", "agent", "manager", "admin", "superadmin"] ;

export function isAdminPortalRole(role) {
  return typeof role === "string" && ADMIN_PORTAL_ROLES.includes(role.trim().toLowerCase() );
}
 






































































































































































































